-- 1) Pull the archived processes of the fix date
--    - exclude missed (nicht_erschienen), like the previous restores
--    - exclude rows without a usable scope, like determineValidScopeId() does
CREATE TEMPORARY TABLE tmp_ba_raw ENGINE=Aria AS
SELECT
  StandortID AS scope_id,
  Datum      AS datum,
  HOUR(STR_TO_DATE(`Timestamp`, '%H:%i:%s')) AS bucket_hour,
  CASE WHEN mitTermin = 1 THEN 'termin' ELSE 'spontan' END AS type,
  CASE WHEN waiting_time = 0 THEN NULL ELSE ROUND(waiting_time, 2) END AS waited_minutes,
  COALESCE(way_time, 0) AS way_minutes
FROM buergerarchiv
WHERE Datum = @fix_date
  AND StandortID > 0
  AND (nicht_erschienen IS NULL OR nicht_erschienen = 0);

-- 2) Aggregate per scope/date/hour/type
CREATE TEMPORARY TABLE tmp_ba_agg ENGINE=Aria AS
SELECT
  scope_id,
  datum,
  bucket_hour,
  type,
  COUNT(*)                                AS cnt,
  ROUND(AVG(waited_minutes), 2)           AS avg_wait_minutes,
  ROUND(AVG(COALESCE(way_minutes, 0)), 2) AS avg_way_minutes
FROM tmp_ba_raw
GROUP BY scope_id, datum, bucket_hour, type;

