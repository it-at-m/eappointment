--   1) Aggregate the archived processes of 2026-08-14 from buergerarchiv per scope/hour/type
--   2) Pivot them into the hourly wartenrstatistik layout
--   3) Refresh scopes that already have a row for that date, insert the missing ones
--
-- Unlike 91757926126 / 91770274084 this migration does not DELETE the day first:
--   * 91763967241 dropped the `scopedate` key, so wartenrstatistik has no unique key on
--     (standortid, datum) and INSERT ... ON DUPLICATE KEY UPDATE would duplicate rows.
--   * hour_*_estimated_waiting_time_* is written during the day by ExchangeWaitingscope and
--     not by the daily run, so it must survive the restore.
--
-- Approximation of the cron: the archive keeps a single `Timestamp` (arrival), so the hour
-- bucket comes from it instead of Uhrzeit / wsm_aufnahmezeit, and mitTermin decides the type.
-- Uses the column names after 91775568666 / 91775568667; buergerarchiv.way_time is already
-- stored in minutes, so no unit conversion is needed.
--
-- Idempotent: re-running recalculates the same averages from buergerarchiv.

SET @fix_date := '2026-08-14';

-- 0) Safety: temp table cleanup
